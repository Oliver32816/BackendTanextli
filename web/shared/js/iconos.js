export function icono(nombre, clase = '') {
  const plantilla = document.createElement('template');
  plantilla.innerHTML = `<svg viewBox="0 0 24 24" ${T} aria-hidden="true" focusable="false" class="${clase}">${RUTAS[nombre] || ''}</svg>`;
  return plantilla.content.firstElementChild;
}

// Para elementos escritos en el HTML: <span data-icono="audio"></span>
export function pintarIconos(raiz = document) {
  raiz.querySelectorAll('[data-icono]').forEach((nodo) => {
    nodo.replaceWith(icono(nodo.dataset.icono, nodo.className));
  });
}
